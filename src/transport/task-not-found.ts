/**
 * 「task 不存在」的**唯一措辞**。
 *
 * 为什么值得为一行字符串建一个模块：这句话出现在 7 处（两条 SSE/取消路径、两条 HTTP
 * 响应、等待器、审批、信号），而它是**对外契约的一半** —— 使用者会 grep 它，宿主会拿它
 * 拼提示文案。此前每处各写一遍模板字面量，改一次措辞要改 7 个地方，漏一个的结果是
 * 「同一件事两种说法」，而且**没有任何测试会红**。
 *
 * 为什么不把状态码也收进来：404 由各抛出点的**错误类**承载（`TaskStreamError` 等自带
 * 404），HTTP 侧显式写 `sendJson(…, 404, …)`。状态码本来就与「哪条路径」绑定，塞进返回
 * 结构只会让调用方多拆一层；这里只隐藏**措辞**这一个决策（信息隐藏的最小单位）。
 */
export function taskNotFound(taskId: string): string {
  return `task 不存在: ${taskId}`;
}
